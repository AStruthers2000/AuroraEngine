#ifndef WINDOW_H
#define WINDOW_H

#include "core/engine.h"

namespace Core
{

class Window
{
public:
    ////////////////////////////////////////////////////////////////////////////////////////////////
    /// @brief Window constructor.
    ///
    /// @param [in] spec - Specification used during window creation/configuration. 
    ////////////////////////////////////////////////////////////////////////////////////////////////
    Window(WindowSpecification const& spec);

    ////////////////////////////////////////////////////////////////////////////////////////////////
    /// @brief Window destructor.
    ////////////////////////////////////////////////////////////////////////////////////////////////
    ~Window();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    /// @brief Creates the SDL window and renderer, configuring SDL in accordance with the window
    ///        specification provided during construction.
    ////////////////////////////////////////////////////////////////////////////////////////////////
    void create();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    /// @brief Destroys the window and renderer.
    ////////////////////////////////////////////////////////////////////////////////////////////////
    void destroy();

    ////////////////////////////////////////////////////////////////////////////////////////////////
    /// @return Returns the SDL_Window managed by this Window.
    ////////////////////////////////////////////////////////////////////////////////////////////////
    SDL_Window* get_sdl_window() const { return m_sdl_window; }

    ////////////////////////////////////////////////////////////////////////////////////////////////
    /// @return Returns the SDL_Renderer managed by this Window.
    ////////////////////////////////////////////////////////////////////////////////////////////////
    SDL_Renderer* get_sdl_renderer() const { return m_sdl_renderer; }

private:
    WindowSpecification m_specification{ };
    SDL_Window* m_sdl_window{ nullptr };
    SDL_Renderer* m_sdl_renderer{ nullptr };
};

} // namespace Core

#endif // WINDOW_H
